def get_grade_band(grade):
    if grade <= 6:
        return "LOWER"
    elif grade <= 8:
        return "MIDDLE"
    else:
        return "UPPER"


def conduct_assessment(subject, grade):
    band = get_grade_band(grade)
    questions = MCQS.get(subject, {}).get(band)

    if not questions:
        print("No questions available for this subject.")
        return 0, 0

    score = 0

    for q in questions:
        print("\n" + q["question"])
        for i, opt in enumerate(q["options"]):
            print(f"{i + 1}. {opt}")

        ans = int(input("Your answer: ")) - 1
        if ans == q["answer"]:
            score += 1

    return score, len(questions)
